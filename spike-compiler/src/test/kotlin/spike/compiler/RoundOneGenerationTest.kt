package spike.compiler

import spike.compiler.assertion.assertContentEquals
import spike.compiler.harness.GeneratedIncludeProcessorProvider
import spike.compiler.harness.IsolatedKsp
import spike.compiler.harness.Libraries
import spike.compiler.harness.SilentProcessorProvider
import spike.compiler.harness.SourceModule
import java.io.File
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class RoundOneGenerationTest {

    private val resources = File("src/test/resources")

    private fun module(name: String, fixture: String, libraries: Libraries = Libraries.Kotlin): SourceModule {
        val work = File("build/tmp/compilations/round_one_$name").apply { deleteRecursively() }
        return SourceModule("main", resources.resolve("$fixture/project/src"), libraries.files(), work)
    }

    private fun generatedBy(module: SourceModule) = module.generatedSources.walk()
        .filter { it.isFile }
        .associate { it.relativeTo(module.generatedSources).path to it.readText() }

    @Test
    fun `nothing else on the classpath means Spike generates in the first round`() {
        val module = module("alone", "entrypoint")
        IsolatedKsp(module, withConverters = false).use { ksp ->
            ksp.run()
            assertEquals(2, ksp.rounds)
        }
        assertContentEquals(resources.resolve("entrypoint/fixtures/main/kotlin"), module.generatedSources)
    }

    @Test
    fun `an unknown processor on the classpath keeps Spike waiting and the output identical`() {
        val alone = module("identical_alone", "entrypoint")
        IsolatedKsp(alone, withConverters = false).use { it.run() }
        val accompanied = module("identical_accompanied", "entrypoint")
        IsolatedKsp(accompanied, withConverters = false).use { ksp ->
            ksp.addProviderJar(File("build/tmp/compilations/round_one_jars"), SilentProcessorProvider::class)
            ksp.run()
            assertEquals(3, ksp.rounds)
        }
        assertEquals(generatedBy(alone), generatedBy(accompanied))
    }

    @Test
    fun `an Include generated by a processor on the classpath joins the graph`() {
        val module = module("co_processor", "generated_include")
        IsolatedKsp(module, withConverters = false).use { ksp ->
            ksp.addProviderJar(File("build/tmp/compilations/round_one_jars"), GeneratedIncludeProcessorProvider::class)
            ksp.run()
            assertTrue(ksp.rounds > 2, "rounds ${ksp.rounds}")
        }
        assertTrue(module.compile().succeeded)
        assertContains(generatedBy(module).getValue("App_Program0.kt"), "generatedClock")
    }

    @Test
    fun `a converter on the classpath keeps Spike waiting for what it generates`() {
        val module = module("converter", "dagger_module", Libraries.Dagger)
        IsolatedKsp(module, withConverters = true).use { ksp ->
            ksp.run()
            assertTrue(ksp.rounds > 2, "rounds ${ksp.rounds}")
        }
        assertTrue(module.compile().succeeded)
    }

    @Test
    fun `an Include from a processor Spike could not discover fails instead of being silently left out`() {
        val module = module("undiscovered", "generated_include_too_late")
        IsolatedKsp(module, withConverters = false).use { ksp ->
            ksp.addProviderJar(
                File("build/tmp/compilations/round_one_jars"),
                GeneratedIncludeProcessorProvider::class,
                discoverable = false,
            )
            assertContains(ksp.runFailing(), "SPIKE-INCLUDE-AFTER-GRAPH")
        }
    }

    @Test
    fun `the ViewModel converter makes Spike wait when the module uses ViewModels`() {
        val module = module("viewmodel", "androidx_viewmodel", Libraries.Androidx)
        IsolatedKsp(module, withConverters = false).use { ksp ->
            ksp.run()
            assertTrue(ksp.rounds > 2, "rounds ${ksp.rounds}")
        }
        assertContentEquals(resources.resolve("androidx_viewmodel/fixtures/main/kotlin"), module.generatedSources)
    }
}
